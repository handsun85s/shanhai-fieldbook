export function matchesProof(values, key) {
  return Array.isArray(values) && values.length===key.length && key.every(i=>values.includes(i));
}
export function restoreInquiries(raw) {
  let saved;
  try {saved=JSON.parse(raw);} catch {saved=null;}
  return Object.fromEntries(inquiries.map(site=>{
    const item=saved?.[site.id];
    const labels=site.points.map((p,i)=>item?.labels?.[i]===p.answer?p.answer:null);
    const proof=labels.every(v=>v!==null)&&matchesProof(item?.proof,site.transfer.key)?[...site.transfer.key]:[];
    return [site.id,{labels,proof}];
  }));
}
